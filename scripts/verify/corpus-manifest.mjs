#!/usr/bin/env node
/**
 * The golden corpus hash manifest (CA, 2026-10-01: commit a manifest of hashes, keep the scenarios
 * out of git).
 *
 * `corpus/MANIFEST.txt` holds one line per scenario from the sources that reproduce bit for bit
 * (authored, grammar, scoring): the scenario id, its step count, and the hash of the state after
 * its last step. A behaviour change in the engine moves a hash, and a moved hash without a manifest
 * change fails this gate, naming every scenario that moved. Regenerating the manifest is then a
 * deliberate, reviewable diff.
 *
 *   node scripts/verify/corpus-manifest.mjs           check `.corpus-out` against the manifest
 *   node scripts/verify/corpus-manifest.mjs --write   rewrite the manifest from `.corpus-out`
 *
 * Run the three sources first (`pnpm corpus:manifest` and `pnpm verify:corpus-manifest` do).
 * The recorded suite, the oracles and the fixtures are not in it: they are large, and the
 * recorded suite's ids follow test names, so they belong to `corpus:verify`, not to a merge gate.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const OUT = process.env.CORPUS_OUT ?? '.corpus-out';
const SOURCES = ['authored', 'grammar', 'scoring'];
const MANIFEST = 'corpus/MANIFEST.txt';
const HEADER = [
  '# Golden corpus hash manifest. Generated by `pnpm corpus:manifest`; checked by `pnpm verify:corpus-manifest`.',
  '# scenarioId  steps  finalHash   (sources: authored, grammar, scoring)',
];

const lines = [];
for (const source of SOURCES) {
  const dir = join(OUT, source);
  if (!existsSync(dir)) {
    console.error(`[corpus-manifest] missing ${dir}; run pnpm corpus:${source} first`);
    process.exit(1);
  }
  for (const file of readdirSync(dir).filter((name) => name.endsWith('.jsonl'))) {
    for (const line of readFileSync(join(dir, file), 'utf8').split('\n')) {
      if (!line.trim()) continue;
      const scenario = JSON.parse(line);
      const steps = scenario.steps ?? [];
      const finalHash = steps.length ? steps[steps.length - 1].hash : scenario.initial.hash;
      lines.push(`${scenario.scenarioId}  ${steps.length}  ${finalHash}`);
    }
  }
}
if (!lines.length) {
  console.error('[corpus-manifest] no scenarios read: refusing to report a clean result over nothing');
  process.exit(1);
}
lines.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const body = [...HEADER, ...lines].join('\n') + '\n';

if (process.argv.includes('--write')) {
  writeFileSync(MANIFEST, body);
  console.log(`[corpus-manifest] wrote ${lines.length} scenarios to ${MANIFEST}`);
  process.exit(0);
}

const committed = existsSync(MANIFEST) ? readFileSync(MANIFEST, 'utf8') : '';
const parse = (text) =>
  new Map(
    text
      .split('\n')
      .filter((line) => line && !line.startsWith('#'))
      .map((line) => [line.split(/\s+/)[0], line]),
  );
const before = parse(committed);
const after = parse(body);
const moved = [...after.keys()].filter((id) => before.has(id) && before.get(id) !== after.get(id));
const added = [...after.keys()].filter((id) => !before.has(id));
const removed = [...before.keys()].filter((id) => !after.has(id));
if (!moved.length && !added.length && !removed.length) {
  console.log(`[corpus-manifest] OK: ${after.size} scenarios, every hash as committed`);
  process.exit(0);
}
console.error('[corpus-manifest] the corpus moved and the manifest did not:');
for (const id of moved) console.error(`  moved    ${id}`);
for (const id of added) console.error(`  added    ${id}`);
for (const id of removed) console.error(`  removed  ${id}`);
console.error(
  'If the behaviour change is intended, run `pnpm corpus:manifest` and commit corpus/MANIFEST.txt with it.',
);
process.exit(1);
