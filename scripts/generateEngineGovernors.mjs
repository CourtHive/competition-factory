#!/usr/bin/env node
/**
 * Codegen: the "which governors each engine carries" table in
 * documentation/docs/engines/hosting-on-a-server.md, written between the
 * ENGINE_GOVERNORS markers.
 *
 * WHY GENERATED. The question the table answers is a runtime one: with the package's one-module-per-file build
 * (`"sideEffects": false`), a shared engine carries only the methods attached by modules that are actually in the
 * bundle. A hand-written list drifts the moment an engine module gains or loses an import.
 *
 * HOW. Every engine exported from src/index.ts (an `export { …Engine… } from './assemblies/engines/…'` line) is
 * bundled ON ITS OWN with esbuild, exactly as a consumer that imports only that engine would get it, and its
 * enumerable function keys are read. Those keys are matched against the function keys of each governor in
 * src/assemblies/governors: a governor is "carried" when every one of its functions is present. A second bundle loads
 * every engine module together (what Node does when it loads the package) to find which exports are one instance.
 *
 * Regenerate: node scripts/generateEngineGovernors.mjs
 * Drift guard: node scripts/generateEngineGovernors.mjs --check
 */

import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join, relative } from 'node:path';
import * as esbuild from 'esbuild';
import * as prettier from 'prettier';
import { REPO_ROOT } from './lib/repoRoot.mjs';
import { tmpdir } from 'node:os';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const INDEX = join(ROOT, 'src/index.ts');
const GOVERNORS = join(ROOT, 'src/assemblies/governors/index.ts');
const PAGE = join(REPO_ROOT, 'documentation/docs/engines/hosting-on-a-server.md');
const START = '<!-- ENGINE_GOVERNORS:START — generated by scripts/generateEngineGovernors.mjs; do not edit by hand -->';
const END = '<!-- ENGINE_GOVERNORS:END -->';

const tmp = mkdtempSync(join(tmpdir(), 'factory-engine-governors-'));
let bundleCount = 0;

async function load(source) {
  bundleCount += 1;
  const entry = join(tmp, `entry${bundleCount}.ts`);
  const outfile = join(tmp, `bundle${bundleCount}.mjs`);
  writeFileSync(entry, source);
  await esbuild.build({
    entryPoints: [entry],
    absWorkingDir: ROOT,
    tsconfig: join(ROOT, 'tsconfig.json'),
    bundle: true,
    platform: 'node',
    format: 'esm',
    outfile,
    logLevel: 'silent',
  });
  // the async engine warns about a missing async state provider while its module evaluates; not ours to report
  const { warn, log } = console;
  console.warn = console.log = () => {};
  try {
    return await import(pathToFileURL(outfile).href);
  } finally {
    console.warn = warn;
    console.log = log;
  }
}

/** `export { a, b as c } from './assemblies/engines/x'` lines of src/index.ts, engine names only. */
function engineExports() {
  const source = readFileSync(INDEX, 'utf8');
  const modules = [];
  for (const match of source.matchAll(/^export\s*\{([^}]+)\}\s*from\s*'(\.\/assemblies\/engines\/[^']+)'/gm)) {
    const names = match[1]
      .split(',')
      .map((part) =>
        part
          .trim()
          .split(/\s+as\s+/)
          .pop(),
      )
      .filter((name) => /Engine/.test(name));
    if (!names.length) continue;
    const path = join(ROOT, 'src', match[2].slice(2));
    const known = modules.find((m) => m.path === path);
    if (known) known.names.push(...names);
    else modules.push({ path, names });
  }
  return modules;
}

const functionKeys = (obj) => Object.keys(obj).filter((key) => typeof obj[key] === 'function');

const { governors } = await load(`export * as governors from ${JSON.stringify(GOVERNORS)};`);
const governorKeys = Object.fromEntries(
  Object.keys(governors)
    .sort()
    .map((name) => [name, functionKeys(governors[name])]),
);

const modules = engineExports();

// every engine module loaded together, as Node loads the package: which exports are the same instance
const together = await load(
  modules.map(({ path, names }) => `export { ${names.join(', ')} } from ${JSON.stringify(path)};`).join('\n'),
);

const rows = [];
for (const { path, names } of modules) {
  const alone = await load(`export { ${names.join(', ')} } from ${JSON.stringify(path)};`);
  const groups = [];
  for (const name of names) {
    const group = groups.find((g) => alone[g[0]] === alone[name]);
    if (group) group.push(name);
    else groups.push([name]);
  }
  for (const group of groups) {
    const value = alone[group[0]];
    const sameAs = modules
      .flatMap((m) => m.names)
      .filter((other) => !group.includes(other) && together[other] === together[group[0]]);
    const definedIn = '`' + relative(join(ROOT, 'src'), path) + '`';
    const exportsCell = group.map((name) => '`' + name + '`').join(', ');
    const sameAsCell = sameAs.length ? sameAs.map((name) => '`' + name + '`').join(', ') : '—';

    if (typeof value === 'function') {
      rows.push([exportsCell, definedIn, 'none: a function (factory or class), not an engine', '—', '—', sameAsCell]);
      continue;
    }

    const keys = new Set(functionKeys(value));
    const carried = [];
    const partial = [];
    for (const [governor, govKeys] of Object.entries(governorKeys)) {
      if (!govKeys.length) continue;
      const present = govKeys.filter((key) => keys.has(key)).length;
      if (present === govKeys.length) carried.push(governor);
      // under half is a shared method name, not the governor: matchUpEngine's scoring methods share a name or two
      // with queryGovernor, and every engine's own core methods are not a governor's
      else if (present * 2 >= govKeys.length) partial.push(`${governor} (${present} of ${govKeys.length})`);
    }
    const covered = new Set(carried.flatMap((governor) => governorKeys[governor]));
    const own = [...keys].filter((key) => !covered.has(key)).length;

    let governorsCell;
    if (carried.length === Object.keys(governorKeys).filter((g) => governorKeys[g].length).length) {
      governorsCell = `all ${carried.length} governors`;
    } else {
      const parts = [];
      if (carried.length) parts.push(carried.map((g) => '`' + g + '`').join(', '));
      if (partial.length) parts.push('some of ' + partial.map((p) => p.replace(/^(\w+)/, '`$1`')).join(', '));
      governorsCell = parts.length ? parts.join('; ') : 'none';
    }
    rows.push([exportsCell, definedIn, governorsCell, String(keys.size), String(own), sameAsCell]);
  }
}

rmSync(tmp, { recursive: true, force: true });

const header = [
  'Export',
  'Defined in',
  'Governors carried when imported alone',
  'Methods',
  'Not from those governors',
  'Same instance as',
];
const table = [
  `| ${header.join(' | ')} |`,
  `| ${header.map(() => '---').join(' | ')} |`,
  ...rows.map((row) => `| ${row.join(' | ')} |`),
].join('\n');

const page = readFileSync(PAGE, 'utf8');
const startAt = page.indexOf(START);
const endAt = page.indexOf(END);
if (startAt < 0 || endAt < startAt) {
  console.error(`[engine-governors] markers not found in ${relative(REPO_ROOT, PAGE)}`);
  process.exit(1);
}
const spliced = page.slice(0, startAt + START.length) + '\n\n' + table + '\n\n' + page.slice(endAt);
const options = (await prettier.resolveConfig(PAGE)) ?? {};
const next = await prettier.format(spliced, { ...options, filepath: PAGE });

if (process.argv.includes('--check')) {
  if (next !== page) {
    console.error(
      '[engine-governors] the governor table in hosting-on-a-server.md is stale; run `node scripts/generateEngineGovernors.mjs`.',
    );
    process.exit(1);
  }
  console.log(`[engine-governors] ok (${rows.length} engine rows)`);
} else {
  writeFileSync(PAGE, next);
  console.log(`[engine-governors] wrote ${rows.length} engine rows to ${relative(REPO_ROOT, PAGE)}`);
}
