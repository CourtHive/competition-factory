#!/usr/bin/env node
/**
 * postbuild — emit per-format type declarations so package.json `exports`
 * can map conditional `types` cleanly (ESM consumers get .d.mts, CJS consumers
 * get .d.cts). publint --strict requires this; without the split, the same
 * .d.ts is interpreted as CJS when resolving via the "import" condition, which
 * causes ambiguous interop typing.
 *
 * (The tree-shakeable ESM build itself is produced by rollup — see
 * rollup.config.mjs `esmExport`. This step only handles the .d.ts variants.)
 */
import fs from 'fs';

const dtsSource = './dist/tods-competition-factory.d.ts';
if (fs.existsSync(dtsSource)) {
  fs.copyFileSync(dtsSource, './dist/tods-competition-factory.d.mts');
  fs.copyFileSync(dtsSource, './dist/tods-competition-factory.d.cts');
}

// The CODES JSON Schema is published at the subpath
// `tods-competition-factory/schema/tournament.schema.json` so consumers that validate records
// (CFS's save path first) read the same declaration the factory's own tests enforce, rather than a
// copy that drifts. `package.json` `files` is `dist` only, so it has to be copied in here.
const schemaSource = './src/global/schema/tournament.schema.json';
if (fs.existsSync(schemaSource)) {
  fs.mkdirSync('./dist/schema', { recursive: true });
  fs.copyFileSync(schemaSource, './dist/schema/tournament.schema.json');
}

// The `tods-competition-factory/governors` subpath. Its ESM target is the governors barrel in the
// preserveModules tree, so `import * as governors from 'tods-competition-factory/governors'` is a
// direct namespace import of that module, which esbuild, rolldown and rollup all shake to the
// governors read. (`import { governors }` from the root cannot shake under esbuild: a namespace
// imported by name becomes an object with a getter for every member.) The CJS shim and the type
// files re-export the root's named governors, read from the barrel's source so a new governor
// joins the subpath without an edit here.
const governorsBarrel = './src/assemblies/governors/index.ts';
const governorsEsm = './dist/esm/assemblies/governors/index.mjs';
if (fs.existsSync(governorsBarrel) && fs.existsSync(governorsEsm)) {
  const names = [...fs.readFileSync(governorsBarrel, 'utf8').matchAll(/^export \* as (\w+) from /gm)].map((m) => m[1]);
  if (!names.length) throw new Error(`postbuild: no governors found in ${governorsBarrel}`);
  const list = names.join(', ');
  const header = '// Generated by postbuild.mjs: the tods-competition-factory/governors subpath.\n';
  fs.writeFileSync(
    './dist/governors.js',
    `${header}'use strict';\nmodule.exports = require('./index.js').governors;\n`,
  );
  fs.writeFileSync('./dist/governors.d.ts', `${header}export { ${list} } from './tods-competition-factory';\n`);
  fs.writeFileSync('./dist/governors.d.mts', `${header}export { ${list} } from './tods-competition-factory.mjs';\n`);
  fs.writeFileSync('./dist/governors.d.cts', `${header}export { ${list} } from './tods-competition-factory.cjs';\n`);
}
