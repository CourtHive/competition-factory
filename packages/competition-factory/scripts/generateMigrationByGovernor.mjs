#!/usr/bin/env node
/**
 * Codegen: the "By governor" tables of documentation/docs/migration-8.0.0.md, written between the
 * MIGRATION_BY_GOVERNOR markers. For each governor that loses a method at 8.0.0: the old call, its replacement and
 * a note.
 *
 * WHY GENERATED. The rows come from the two lists that already drive the `@deprecated` tags
 * (`scripts/lib/deprecations.mjs`): every `scheduled-for-removal` route of `documentation/engine-api-transition.json`,
 * in the governors that row names, and every name of the positional guard list
 * (`src/tests/governors/positionalGovernorFunctions.ts`), in every governor that holds it. A hand-written table
 * would drift from the tags an editor shows. A manifest row with `routes` lists only those member paths (the `query`
 * placement of a function that stays on `mutate`); one with `retainedOn` notes that the engine method stays.
 *
 * WHAT IS CHECKED. The governors and the `tools` / `availability` exports are loaded from source with esbuild. Every
 * old call must exist on its governor (so the table never lists a route 7.x does not have), and every replacement
 * written as a path must resolve to a function (so it never names a home that does not exist).
 *
 * Regenerate: node scripts/generateMigrationByGovernor.mjs
 * Drift guard: node scripts/generateMigrationByGovernor.mjs --check
 */

import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join, relative } from 'node:path';
import * as esbuild from 'esbuild';
import * as prettier from 'prettier';
import { REPO_ROOT } from './lib/repoRoot.mjs';
import { MANIFEST_PATH, loadDeprecations } from './lib/deprecations.mjs';
import { tmpdir } from 'node:os';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const PAGE = join(REPO_ROOT, 'documentation/docs/migration-8.0.0.md');
const START =
  '<!-- MIGRATION_BY_GOVERNOR:START — generated by scripts/generateMigrationByGovernor.mjs; do not edit by hand -->';
const END = '<!-- MIGRATION_BY_GOVERNOR:END -->';

/** Governors retired whole at 8.0.0. */
const RETIRED = new Set(['matchUpFormatGovernor']);

/** The publishing predicates change more than the import. */
const PUBLISHING_NOTE = 'Pass `asOf`: optional in 7.x, required in 8.0.0.';

const tmp = mkdtempSync(join(tmpdir(), 'factory-migration-governors-'));
async function load(source) {
  const entry = join(tmp, 'entry.ts');
  const outfile = join(tmp, 'bundle.mjs');
  writeFileSync(entry, source);
  await esbuild.build({
    entryPoints: [entry],
    absWorkingDir: ROOT,
    tsconfig: join(ROOT, 'tsconfig.json'),
    bundle: true,
    platform: 'node',
    format: 'esm',
    outfile,
    logLevel: 'silent',
  });
  const { warn, log } = console;
  console.warn = console.log = () => {};
  try {
    return await import(pathToFileURL(outfile).href);
  } finally {
    console.warn = warn;
    console.log = log;
  }
}

const surface = await load(
  [
    `export * as governors from ${JSON.stringify(join(ROOT, 'src/assemblies/governors/index.ts'))};`,
    `export { tools, availability } from ${JSON.stringify(join(ROOT, 'src/index.ts'))};`,
  ].join('\n'),
);
rmSync(tmp, { recursive: true, force: true });

const resolvePath = (path) =>
  path.split('.').reduce((obj, key) => (obj == null ? undefined : obj[key]), {
    tools: surface.tools,
    availability: surface.availability,
    ...surface.governors,
  });
const isPath = (value) => typeof value === 'string' && /^(tools|availability|\w+Governor)(\.\w+)+$/.test(value);

const problems = [];
const manifest = JSON.parse(readFileSync(join(REPO_ROOT, MANIFEST_PATH), 'utf8'));
const rowsOf = new Map(manifest.methods.map((m) => [m.name, m]));
const { names } = loadDeprecations({ REPO_ROOT, PACKAGE_ROOT: ROOT });
const governorNames = Object.keys(surface.governors).filter((g) => /Governor$/.test(g));

const code = (s) => `\`${s}\``;
const byGovernor = new Map(); // governor -> [{ old, replacement, note }]
const add = (governor, row) => {
  if (!byGovernor.has(governor)) byGovernor.set(governor, []);
  byGovernor.get(governor).push(row);
};

for (const [name, entry] of names) {
  const route = rowsOf.get(name);
  const raw = route?.replacement ?? entry.destination ?? null;
  const governors = entry.governors
    ? [...entry.governors]
    : governorNames.filter((g) => typeof surface.governors[g][name] === 'function');
  if (!governors.length) problems.push(`${name}: no governor holds it`);

  let replacement;
  const notes = [];
  if (raw && typeof raw === 'object') {
    replacement = 'Several routes';
    notes.push(`See [the supported routes](/docs/${route.destination}#supported-migration-routes).`);
  } else if (isPath(raw)) {
    replacement = code(raw);
    if (typeof resolvePath(raw) !== 'function') problems.push(`${name}: replacement ${raw} does not resolve`);
    if (raw.split('.').pop() !== name) notes.push('Renamed.');
  } else if (raw) {
    replacement = raw.replace(/\b(getPublishState)\b/, '`$1`');
    notes.push('It takes a whole record.');
  } else {
    replacement = 'None';
    notes.push(`See [its reference](/docs/${route.destination}).`);
  }
  if (entry.positional && isPath(raw)) notes.unshift('Positional arguments: call it directly, not through an engine.');
  else if (isPath(raw)) notes.unshift('The same params object.');
  if (typeof raw === 'string' && raw.startsWith('tools.publishing.')) notes.push(PUBLISHING_NOTE);
  if (entry.retainedOn?.size)
    notes.push(
      `The engine method stays: ${[...entry.retainedOn].map(code).join(' and ')} keep${entry.retainedOn.size > 1 ? '' : 's'} the name.`,
    );

  if (entry.routes) notes.push('Only this placement goes.');
  const olds = entry.routes ? [...entry.routes] : governors.map((governor) => `${governor}.${name}`);
  for (const old of olds) {
    const governor = old.split('.')[0];
    if (typeof resolvePath(old) !== 'function') problems.push(`${old}: not on the governor in this build`);
    const note = [...notes, RETIRED.has(governor) ? 'The governor is retired.' : ''].filter(Boolean).join(' ');
    add(governor, { old: code(old), replacement, note });
  }
}

if (problems.length) {
  console.error(`[migration-governors] ${problems.length} problem(s):\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

const governors = [...byGovernor.keys()].sort((a, b) => a.localeCompare(b));
let total = 0;
const sections = governors.map((governor) => {
  const rows = byGovernor.get(governor).sort((a, b) => a.old.localeCompare(b.old));
  total += rows.length;
  return [
    `#### ${governor}`,
    '',
    '| Old call | Replacement | Notes |',
    '| --- | --- | --- |',
    ...rows.map((r) => `| ${r.old} | ${r.replacement} | ${r.note || '—'} |`),
  ].join('\n');
});

const page = readFileSync(PAGE, 'utf8');
const startAt = page.indexOf(START);
const endAt = page.indexOf(END);
if (startAt < 0 || endAt < startAt) {
  console.error(`[migration-governors] markers not found in ${relative(REPO_ROOT, PAGE)}`);
  process.exit(1);
}
const spliced = page.slice(0, startAt + START.length) + '\n\n' + sections.join('\n\n') + '\n\n' + page.slice(endAt);
const options = (await prettier.resolveConfig(PAGE)) ?? {};
const next = await prettier.format(spliced, { ...options, filepath: PAGE });
const summary = `${total} rows in ${governors.length} governors`;

if (process.argv.includes('--check')) {
  if (next !== page) {
    console.error(
      '[migration-governors] the by-governor tables in migration-8.0.0.md are stale; run `node scripts/generateMigrationByGovernor.mjs`.',
    );
    process.exit(1);
  }
  console.log(`[migration-governors] ok (${summary})`);
} else {
  writeFileSync(PAGE, next);
  console.log(`[migration-governors] wrote ${summary} to ${relative(REPO_ROOT, PAGE)}`);
}
