#!/usr/bin/env node
/** Generate engine signatures, direct mount names and query-purity kinds from one descriptor inventory. */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readDescriptors } from './engineMethodDescriptors.mjs';
import { loadDeprecations } from './lib/deprecations.mjs';
import { REPO_ROOT } from './lib/repoRoot.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputDir = join(ROOT, 'src/assemblies/engines/types');
const OUT = join(outputDir, 'methodSignatures.ts');
const DIRECT_OUT = join(outputDir, 'asyncEngineDirectMethods.ts');
const { descriptors, directNames } = readDescriptors(ROOT, outputDir);
// The routes leaving the engines at 8.0.0 (transition manifest + positional guard list) carry their `@deprecated`
// message here for in-repo editors; `postbuild.mjs` injects the same tags into the built declarations, which lose
// every comment (`removeComments`).
const { names: deprecated } = loadDeprecations({ REPO_ROOT, PACKAGE_ROOT: ROOT });
const resolved = descriptors
  .filter((entry) => entry.source)
  .map(({ publicName, source }) => ({ publicName, ...source }));

// --- group by source path so the import list stays clean ---
const byPath = new Map();
for (const r of resolved) {
  if (!byPath.has(r.sourcePath)) byPath.set(r.sourcePath, []);
  byPath.get(r.sourcePath).push(r);
}

// Import order is decided after the lines are built, not here: the convention
// sorts by EMITTED LINE length, and the line carries `import type { <names> } from `
// on top of the path — which is why sorting the paths alone produced an inverted
// block (234 inversions, measured 2026-09-13). Paths are ordered here only to keep
// the emit deterministic; `importChunks` is re-sorted below.
const sortedPaths = Array.from(byPath.keys()).sort((a, b) => b.length - a.length || a.localeCompare(b));

// --- emit ---
const lines = [];
lines.push('/**');
lines.push(' * MethodSignatures — per-method typed params + returns for the engine surface.');
lines.push(' *');
lines.push(' * AUTO-GENERATED by `pnpm gen:method-signatures`. CI runs');
lines.push(' * `pnpm check:method-signatures` and fails on drift. Do not hand-edit.');
lines.push(' *');
lines.push(' * Sources: governor barrels under `src/assemblies/governors/` and the');
lines.push(" * engine assembly's lambda mounts (`engineStart.ts`). Each entry wraps");
lines.push(' * `typeof <sourceFn>` with `EngineMethod` so the source signature is');
lines.push(' * transformed into the engine-call shape — auto-resolved keys (event,');
lines.push(' * drawDefinition, tournamentRecord, etc.) become optional, hint keys');
lines.push(' * (drawId, eventId, ...) are admitted, and 0-arg calls are allowed on');
lines.push(' * methods that need nothing beyond engine state. See `EngineMethod`');
lines.push(' * doc in `engineTypes.ts` for the rationale.');
lines.push(' *');
lines.push(' * Methods not in this map fall through to the `(...args: any[]) => any`');
lines.push(' * fallback on `FactoryEngineTyped`; that set shrinks as the parser');
lines.push(' * resolves more of the public surface over time.');
lines.push(' */');
lines.push('');
lines.push("import type { EngineMethod } from './engineTypes';");
lines.push('');

const importChunks = [];
for (const path of sortedPaths) {
  const entries = byPath
    .get(path)
    .slice()
    .sort((a, b) => a.sourceName.localeCompare(b.sourceName));
  // dedupe sourceName per path
  const uniq = Array.from(new Map(entries.map((e) => [e.sourceName, e])).values());
  // Mirror Prettier's collapse behavior (printWidth 120 in .prettierrc.json)
  // so prebuild output stays clean without a follow-up `prettier --write`.
  // A LONE specifier always stays on one line no matter how long: Prettier will
  // not break `import type { x } from '<very long path>';`, because breaking it
  // does not shorten the offending part. Emitting it multi-line here makes the
  // pre-commit `prettier --write` collapse it again and `check:method-signatures`
  // report drift — which is exactly what happened on the first pass of #4861.
  const single = `import type { ${uniq.map((e) => e.sourceName).join(', ')} } from '${path}';`;
  if (uniq.length === 1 || single.length <= 120) {
    importChunks.push({ multiline: false, width: single.length, path, lines: [single] });
  } else {
    importChunks.push({
      multiline: true,
      width: single.length,
      path,
      lines: [`import type {`, ...uniq.map((e) => `  ${e.sourceName},`), `} from '${path}';`],
    });
  }
}

// CourtHive convention: within a section single-line imports descend by line
// length, and multi-line destructured imports come last. Ties break on path so
// the output is stable across runs (`pnpm check:method-signatures` diffs it).
const chunkOrder = (a, b) =>
  Number(a.multiline) - Number(b.multiline) || b.width - a.width || a.path.localeCompare(b.path);
for (const chunk of importChunks.sort(chunkOrder)) lines.push(...chunk.lines);

lines.push('');
lines.push('export interface MethodSignatures {');
const byPublic = resolved.slice().sort((a, b) => a.publicName.localeCompare(b.publicName));
for (const e of byPublic) {
  const deprecation = deprecated.get(e.publicName);
  if (deprecation) lines.push(`  /** @deprecated ${deprecation.message} */`);
  lines.push(`  ${e.publicName}: EngineMethod<typeof ${e.sourceName}>;`);
}
lines.push('}');
lines.push('');

const content = lines.join('\n');
// These mounts bypass asyncEngineInvoke. Keep their inventory generated so a newly
// mounted synchronous helper cannot silently acquire a Promise return type.
const directContent = [
  '/** Generated by scripts/generateMethodSignatures.mjs. Do not hand-edit. */',
  'export type AsyncEngineDirectMethod =',
  ...directNames.map((name, index) => `  | '${name}'${index === directNames.length - 1 ? ';' : ''}`),
  '',
].join('\n');

const kinds = Object.fromEntries(
  descriptors.map(({ publicName, kind }) => [publicName, kind]).sort(([a], [b]) => a.localeCompare(b)),
);
const outputs = [
  [OUT, content],
  [DIRECT_OUT, directContent],
  [join(ROOT, 'src/tests/testHarness/queryPurity/methodKinds.json'), JSON.stringify(kinds, null, 2) + '\n'],
];
const check = process.argv.includes('--check');
for (const [path, generated] of outputs) {
  if (!check) writeFileSync(path, generated);
  else if (!existsSync(path) || readFileSync(path, 'utf8') !== generated) {
    console.error(`[engine-methods] stale ${path}; run pnpm gen:method-signatures`);
    process.exitCode = 1;
  }
}
console.log(
  `[engine-methods] ${resolved.length} signatures, ${directNames.length} direct mounts, ${descriptors.length} kinds`,
);
