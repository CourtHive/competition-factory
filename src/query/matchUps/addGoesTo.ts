type AddGoesToArgs = {
  inContextDrawMatchUps?: HydratedMatchUp[];
  drawDefinition: DrawDefinition;
  matchUpsMap?: MatchUpsMap;
};
export type GoesToMap = {
  loserMatchUpIds: { [matchUpId: string]: string };
  winnerMatchUpIds: { [matchUpId: string]: string };
};
type AddGoesToResult =
  | (ResultType & { error: ErrorType; inContextDrawMatchUps?: undefined; goesToMap?: undefined })
  | { inContextDrawMatchUps?: HydratedMatchUp[]; goesToMap: GoesToMap; error?: undefined };

export function addGoesTo({ inContextDrawMatchUps, drawDefinition, matchUpsMap }: AddGoesToArgs): AddGoesToResult {
  if (!drawDefinition) return { error: MISSING_DRAW_DEFINITION };

  const goesToMap: GoesToMap = { loserMatchUpIds: {}, winnerMatchUpIds: {} };

  // Both args are optional, so all four combinations must work. Previously the map was
  // only ever built inside `if (!inContextDrawMatchUps)`, which meant the one combination
  // an integrator would most naturally reach for — "here are the matchUps I already
  // flattened, enrich them" — dereferenced an undefined map and threw a bare
  // `Cannot read properties of undefined` out of getMappedStructureMatchUps.
  //
  // Resolve each independently, and use `??=` so a caller-supplied array is never
  // replaced by a freshly-flattened one: callers pass their own array precisely because
  // they intend THAT array to be mutated in place.
  if (!inContextDrawMatchUps || !matchUpsMap) {
    const resolved = getAllDrawMatchUps({ inContext: true, drawDefinition, matchUpsMap });
    inContextDrawMatchUps ??= resolved.matchUps;
    matchUpsMap ??= resolved.matchUpsMap;
  }

  const hasFinishingPositionRanges = matchUpsMap?.drawMatchUps.some((m) => m.finishingPositionRange);

  // NOTE: handles drawDefinitions in TODS files not generated by the factory
  // IF: there is only one structure present... as is the case with tods-xls-converter
  if (
    !hasFinishingPositionRanges &&
    drawDefinition?.structures?.length === 1 &&
    !structuresOf(drawDefinition?.structures[0])
  ) {
    const matchUps = matchUpsMap?.drawMatchUps ?? [];
    addFinishingRounds({ matchUps });
  }

  // built once for this call: every matchUp's targets are read from the same draw
  const targetIndex = buildTargetIndex(inContextDrawMatchUps);
  const storedById = new Map<string, Map<string, MatchUp>>();
  const storedMatchUp = (structureId: string, matchUpId: string) => {
    if (!storedById.has(structureId)) {
      const byId = new Map<string, MatchUp>();
      for (const matchUp of getMappedStructureMatchUps({ matchUpsMap, structureId })) {
        if (!byId.has(matchUp.matchUpId)) byId.set(matchUp.matchUpId, matchUp);
      }
      storedById.set(structureId, byId);
    }
    return storedById.get(structureId)?.get(matchUpId);
  };

  for (const inContextMatchUp of (inContextDrawMatchUps ?? []).filter(({ collectionId }) => !collectionId)) {
    const { matchUpId, structureId } = inContextMatchUp;
    const targetData = positionTargets({
      asReferences: true, // read here, never changed
      inContextDrawMatchUps,
      drawDefinition,
      targetIndex,
      matchUpId,
    });
    // a malformed round link is an error, never an edge that is quietly not written
    if (targetData.error)
      return { ...decorateResult({ result: targetData, stack: 'addGoesTo' }), error: targetData.error };
    const { winnerMatchUp, loserMatchUp } = targetData.targetMatchUps;
    const winnerMatchUpId = winnerMatchUp?.matchUpId;
    const loserMatchUpId = loserMatchUp?.matchUpId;

    const matchUp = storedMatchUp(structureId, matchUpId);

    if (matchUp) {
      if (winnerMatchUpId) {
        goesToMap.winnerMatchUpIds[matchUp.matchUpId] = winnerMatchUpId;
        Object.assign(matchUp, { winnerMatchUpId });
        Object.assign(inContextMatchUp, { winnerMatchUpId });
      }
      if (loserMatchUpId) {
        goesToMap.loserMatchUpIds[matchUp.matchUpId] = loserMatchUpId;
        inContextMatchUp.loserMatchUpId = loserMatchUpId;
        matchUp.loserMatchUpId = loserMatchUpId;

        if (inContextMatchUp.finishingPositionRange) {
          const loserRange = loserMatchUp.finishingPositionRange && [
            ...inContextMatchUp.finishingPositionRange.loser,
            ...loserMatchUp.finishingPositionRange.loser,
          ];
          // undefined where the loser target carries no range: written as it always was
          const loser = loserRange && [Math.min(...loserRange), Math.max(...loserRange)];
          Object.assign(inContextMatchUp.finishingPositionRange, { loser });
          (matchUp.finishingPositionRange as { loser?: number[] }).loser = loser;
        }
      }
    }
  }

  return { inContextDrawMatchUps, goesToMap };
}

/**
 * Does the draw STORE the edges `addGoesTo` derives — `winnerMatchUpId` and `loserMatchUpId`?
 *
 * A draw the factory generated does: generation, playoff generation and `attachStructures` all write
 * them. A record that came from somewhere else may not — an older record, or a file the factory did
 * not produce — and the exit cascade reads the STORED ids (`hasPropagatedExitDownstream`,
 * `getExitWinningSide`, `getHeldExit`), so on such a draw it decides differently. Measured
 * 2026-10-01: the same hundred matrix cells played on draws with the ids stripped ended in a
 * different draw 44 times when nothing restored them.
 *
 * This is the cheap question, asked of the stored matchUps alone, that says whether the expensive
 * answer (`addGoesTo`: a hydration and a `positionTargets` per matchUp) is needed at all:
 *
 *  - an elimination structure with more than one round holds a matchUp with a `winnerMatchUpId`;
 *  - a structure a LOSER link leaves holds a matchUp with a `loserMatchUpId`.
 *
 * It asks whether a structure has ANY, not whether it has all: a final has no winner target, and
 * `removeStructure` deletes the ids that pointed into what it removed. `false` is the safe answer —
 * it costs a derivation, never a wrong edge.
 */
export function hasStoredGoesTo({ drawDefinition }: { drawDefinition: DrawDefinition }): boolean {
  const loserSources = new Set(
    (drawDefinition.links ?? []).filter((link) => link.linkType === LOSER).map((link) => link.source?.structureId),
  );

  return (drawDefinition.structures ?? []).every((structure) => {
    const matchUps = matchUpsOf(structure) ?? [];
    if (loserSources.has(structure.structureId) && !matchUps.some((matchUp) => matchUp.loserMatchUpId)) return false;
    if (structure.finishingPosition === WIN_RATIO || structuresOf(structure)) return true;
    // the ordinary answer is found on the first matchUp looked at; the rounds are counted only for
    // a structure that holds no winner edge at all, to tell a single round from a missing edge
    if (matchUps.some((matchUp) => matchUp.winnerMatchUpId)) return true;
    return new Set(matchUps.map((matchUp) => matchUp.roundNumber)).size < 2;
  });
}

/**
 * Give a draw that does not store its edges the edges; a draw that does is left alone.
 *
 * A caller that already holds the draw in context hands the view over with its map. `addGoesTo`
 * then writes the edges onto that view as well as onto the stored matchUps, and hydrates nothing:
 * the repair costs a `positionTargets` per matchUp, once, and the draw stores its edges from then on.
 */
export function ensureGoesTo({ inContextDrawMatchUps, drawDefinition, matchUpsMap }: AddGoesToArgs) {
  if (hasStoredGoesTo({ drawDefinition })) return undefined;
  const result = addGoesTo({ inContextDrawMatchUps, drawDefinition, matchUpsMap });
  return result.error ? result : undefined;
}

/**
 * What `ensureGoesTo` will write on a draw, held so that a call which is then refused can write it back.
 *
 * CA, 2026-10-18: "no, a refused call does not store a draw's missing edges. v1 should no longer do so." The edges are
 * still written once, before anything is decided on them, because the cascade decides on the STORED ids (#5086); what
 * that write touches is held here, before it, and the function returned puts it back on an error. A call that
 * succeeds keeps what was written, and the draw stores its edges from then on.
 *
 * A draw that stores its edges has nothing written, so nothing is held: `undefined`, for the cost of the
 * `hasStoredGoesTo` walk. Otherwise each stored matchUp's `winnerMatchUpId`, `loserMatchUpId`, `finishingRound` and
 * `finishingPositionRange` (the object, and what it held) is noted, which is all `addGoesTo` and the finishing rounds
 * it may add write. They are written back into the same matchUps, and the same range objects, as the differential
 * path writes back what a divergence touched.
 *
 * `written` says whether any of what was held has changed since: a call that succeeds announces the draw once when it
 * did (CA, 2026-10-18: "Option 2"), with a `MODIFY_DRAW_DEFINITION` rather than a `MODIFY_MATCHUP` per matchUp.
 */
export function holdGoesTo({
  drawDefinition,
  matchUpsMap,
}: {
  drawDefinition?: DrawDefinition;
  matchUpsMap?: MatchUpsMap;
}): GoesToHold | undefined {
  if (!drawDefinition || hasStoredGoesTo({ drawDefinition })) return undefined;
  const matchUps = (matchUpsMap ?? getMatchUpsMap({ drawDefinition })).drawMatchUps;
  const held = matchUps.map((matchUp) => {
    const range = matchUp.finishingPositionRange;
    return {
      storedValues: GOES_TO_FIELDS.map((key) => [key, key in matchUp, matchUp[key]] as const),
      range: range && { object: range, values: { ...range } },
      matchUp,
    };
  });

  const release = () => {
    for (const { matchUp, storedValues, range } of held) {
      const target = matchUp as Record<(typeof GOES_TO_FIELDS)[number], unknown>;
      for (const [key, present, value] of storedValues) {
        if (present) target[key] = value;
        else delete target[key];
      }
      if (range) {
        for (const key of Object.keys(range.object)) if (!(key in range.values)) delete range.object[key];
        Object.assign(range.object, range.values);
        matchUp.finishingPositionRange = range.object;
      } else {
        delete matchUp.finishingPositionRange;
      }
    }
  };

  const written = () =>
    held.some(({ matchUp, storedValues, range }) => {
      const moved = storedValues.some(([key, present, value]) => {
        const isPresent = key in matchUp;
        return isPresent !== present || matchUp[key] !== value;
      });
      if (moved) return true;
      if (!range) return !!matchUp.finishingPositionRange;
      if (matchUp.finishingPositionRange !== range.object) return true;
      return JSON.stringify(range.object) !== JSON.stringify(range.values);
    });

  return { release, written };
}

export type GoesToHold = { release: () => void; written: () => boolean };

const GOES_TO_FIELDS = ['winnerMatchUpId', 'loserMatchUpId', 'finishingRound'] as const;

/**
 * A draw that does not store its edges is given them (CA, 2026-10-16: a one-time backfill of stored converted records,
 * and this migration a standard requirement of ingest). `migrateTournamentRecord` runs it on every draw, and
 * `addDrawDefinition` on the draw it adds (CA, 2026-10-18): a draw built outside the factory is stored with its edges.
 *
 * The factory stores `winnerMatchUpId` / `loserMatchUpId` on every draw it generates, and `finishingPositionRange` on
 * every matchUp; a record converted from elsewhere may hold neither. A query used to write them as a side effect, which
 * the server then saved, so a converted record gained them only once something had scheduled it. No query writes now
 * (`getMatchUpDependencies` derives on a copy), so the migration writes what `addGoesTo` derives: the edges, the loser
 * ranges widened over the loser target, and a lone foreign structure's finishing rounds.
 *
 * Unconditional, like `compactDrawPositions`: an edge is never a legacy fact worth keeping out. A draw with a MALFORMED
 * ROUND LINK (CA, 2026-10-06: it is an error) is left as it was: `addGoesTo` stops where it meets the link, so the
 * derivation is tried on a copy first and the draw is never half given its edges. An AD_HOC draw has no positions to
 * derive from (its rounds are paired, not linked), so it is skipped, as the query's write always skipped it.
 */
export function storeGoesTo(drawDefinition: DrawDefinition): number {
  return storeGoesToResult(drawDefinition).stored;
}

/**
 * `storeGoesTo`, saying WHY a draw was left as it was: the error the derivation met (a malformed round link), so a
 * caller that reports, as `migrateTournamentRecord` does, need not swallow it. `stored` is what `storeGoesTo` returns.
 */
export function storeGoesToResult(drawDefinition: DrawDefinition): { stored: number; error?: ResultType } {
  if (hasStoredGoesTo({ drawDefinition }) && !needsFinishingRounds(drawDefinition)) return { stored: 0 };
  if (drawDefinition.structures?.some((structure) => isAdHoc({ structure }))) return { stored: 0 };
  const derived = addGoesTo({ drawDefinition: makeDeepCopy(drawDefinition, false, true) });
  if (derived.error) return { stored: 0, error: derived };
  // counted only where a stored value changed: a draw whose edges cannot be derived (no links, nothing to follow) is
  // asked again on every run and given nothing each time
  const before = storedGoesTo(drawDefinition);
  addGoesTo({ drawDefinition });
  return { stored: storedGoesTo(drawDefinition) === before ? 0 : 1 };
}

function storedGoesTo(drawDefinition: DrawDefinition): string {
  const structures = (drawDefinition.structures ?? []).flatMap((structure) => [
    structure,
    ...(structuresOf(structure) ?? []),
  ]);
  return JSON.stringify(
    structures
      .flatMap((structure) => matchUpsOf(structure) ?? [])
      .map(({ winnerMatchUpId, loserMatchUpId, finishingPositionRange, finishingRound }) => [
        winnerMatchUpId,
        loserMatchUpId,
        finishingPositionRange,
        finishingRound,
      ]),
  );
}

/**
 * The draw as a READ should see it, without writing to it: a draw that does not store what `addGoesTo` derives is read
 * from a copy that carries it (`storeGoesTo` on the copy), and the draw handed in is never changed. A draw that owes
 * nothing, or that nothing can be derived for (an AD_HOC draw), is returned as it is and costs no copy.
 */
export function drawWithDerivedGoesTo(drawDefinition: DrawDefinition): DrawDefinition {
  if (hasStoredGoesTo({ drawDefinition }) && !needsFinishingRounds(drawDefinition)) return drawDefinition;
  if (drawDefinition.structures?.some((structure) => isAdHoc({ structure }))) return drawDefinition;
  const copy = makeDeepCopy(drawDefinition, false, true);
  storeGoesTo(copy);
  return copy;
}

/**
 * The edges for a READ that must still refuse a MALFORMED ROUND LINK (CA, 2026-10-06: it is an error):
 * `getMatchUpDependencies`. It never writes. A draw that does not store its edges has them derived on a copy and
 * handed back as the `goesToMap`; the stored draw is left as it was. It used to be repaired here, the edges, a widened
 * `finishingPositionRange.loser` and a lone foreign structure's finishing rounds all written by a query.
 *
 * A draw that stores its edges derives nothing, so the link is asked about on its own: once per round of each
 * structure, which is the question `positionTargets` asks of every matchUp in that round. The error is the same one; on
 * a draw with several malformed links it may name a different matchUp than the derivation would have reached first.
 */
export function derivedGoesToOrLinkError({ drawDefinition }: { drawDefinition: DrawDefinition }) {
  if (!hasStoredGoesTo({ drawDefinition })) {
    const result = addGoesTo({ drawDefinition: makeDeepCopy(drawDefinition, false, true) });
    return result.error ? result : { goesToMap: result.goesToMap, error: undefined };
  }

  const structures = (drawDefinition.structures ?? []).flatMap((structure) => [
    structure,
    ...(structuresOf(structure) ?? []),
  ]);
  for (const structure of structures) {
    const askedRounds = new Set<number | undefined>();
    for (const matchUp of matchUpsOf(structure) ?? []) {
      if (matchUp.collectionId || askedRounds.has(matchUp.roundNumber)) continue;
      askedRounds.add(matchUp.roundNumber);
      const inContextMatchUp = { ...matchUp, structureId: structure.structureId } as HydratedMatchUp;
      const targetData = positionTargets({
        asReferences: true,
        inContextMatchUp,
        drawDefinition,
        matchUpId: matchUp.matchUpId,
      });
      if (targetData.error)
        return { ...decorateResult({ result: targetData, stack: 'derivedGoesTo' }), error: targetData.error };
    }
  }
  return undefined;
}

/**
 * What `addGoesTo` does besides the edges: a lone structure the factory did not generate, none of whose matchUps
 * carries a `finishingPositionRange`, is given its finishing rounds. A one-round draw stores no edges and needs none
 * (`hasStoredGoesTo` is true), so the edges alone do not say whether this is still owed. Asked as `addGoesTo` asks it.
 */
export function needsFinishingRounds(drawDefinition: DrawDefinition): boolean {
  const structures = drawDefinition.structures ?? [];
  if (structures.length !== 1 || structuresOf(structures[0])) return false;
  return !(matchUpsOf(structures[0]) ?? []).some(
    (matchUp) =>
      !!matchUp.finishingPositionRange ||
      !!matchUp.tieMatchUps?.some((tieMatchUp) => tieMatchUp.finishingPositionRange),
  );
}

/**
 * The event as a READ should see it, without writing to it: a draw that does not store what `addGoesTo` derives is
 * read from a copy that carries it (P54). `getParticipants({ withMatchUps | withRankingProfile })` used to repair the
 * STORED draw for this (`getMatchUpDependencies`, result discarded), a query that wrote. Measured 2026-10-15 on
 * Button's ingest corpus: it wrote on 40 of 414 records with draws (all converted outside the factory), never on a
 * draw the factory made.
 *
 * What hydration reads is what the repair left behind: the edges, `finishingPositionRange.loser` widened over the loser
 * target (it reaches the ranking profile and so points), and a lone foreign structure's finishing rounds. The draws the
 * repair skipped are skipped here: one holding a matchUp without a roundPosition (tie matchUps carry none). A malformed
 * round link stops the derivation where it is met, with what came before it derived, as it stopped the repair.
 */
export function eventWithDerivedGoesTo(event: Event): Event {
  let derived = false;
  const drawDefinitions = (event.drawDefinitions ?? []).map((drawDefinition) => {
    const owed = !hasStoredGoesTo({ drawDefinition }) || needsFinishingRounds(drawDefinition);
    if (!owed || hasMatchUpWithoutRoundPosition(drawDefinition)) return drawDefinition;
    const copy = makeDeepCopy(drawDefinition, false, true);
    addGoesTo({ drawDefinition: copy });
    derived = true;
    return copy;
  });
  return derived ? { ...event, drawDefinitions } : event;
}

function hasMatchUpWithoutRoundPosition(drawDefinition: DrawDefinition) {
  return (drawDefinition.structures ?? [])
    .flatMap((structure) => [structure, ...(structuresOf(structure) ?? [])])
    .flatMap((structure) => matchUpsOf(structure) ?? [])
    .some((matchUp) => !matchUp.roundPosition || matchUp.tieMatchUps?.some((tieMatchUp) => !tieMatchUp.roundPosition));
}
