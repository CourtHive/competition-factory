import mocksEngine from '@Assemblies/engines/mock';
import addFormats from 'ajv-formats';
import { expect, it } from 'vitest';
import fs from 'fs-extra';
import Ajv from 'ajv';

import {
  COMPASS,
  CURTIS_CONSOLATION,
  FEED_IN,
  FEED_IN_CHAMPIONSHIP_TO_SF,
  FIRST_MATCH_LOSER_CONSOLATION,
  FIRST_ROUND_LOSER_CONSOLATION,
  MODIFIED_FEED_IN_CHAMPIONSHIP,
  ROUND_ROBIN,
  ROUND_ROBIN_WITH_PLAYOFF,
} from '@Constants/drawDefinitionConstants';

const ajv = new Ajv({ allowUnionTypes: true, verbose: true, allErrors: true });
ajv.addFormat('date-time', (dateTime: any) => {
  if (typeof dateTime === 'object') dateTime = dateTime.toISOString();
  return !Number.isNaN(Date.parse(dateTime));
});
addFormats(ajv);

const schema = JSON.parse(
  fs.readFileSync('./src/global/schema/tournament.schema.json', {
    encoding: 'utf8',
  }),
);
const validate = ajv.compile(schema);

const sourcePath = './src/tests/testHarness';
// `.includes`, not `indexOf(...) === undefined`. `indexOf` returns a NUMBER, so the old
// `filename.indexOf('.8') === undefined` was always false and `filenames` was always EMPTY —
// `it.each([])` registers no tests and vitest does not complain, so this suite reported green
// while validating none of the 16 TODS files. The read path below was wrong too
// (`src/global/testHarness`, which does not exist), so either bug alone was fatal.
const filenames: any[] = fs
  .readdirSync(sourcePath)
  .filter((filename) => filename.includes('.tods.json') && !filename.includes('.8')); // TODS v0.8 is not validated

// Guard the guard: if the glob ever goes empty again, fail loudly instead of silently passing.
it('finds TODS files to validate', () => {
  expect(filenames.length).toBeGreaterThan(0);
});

it.each(filenames)('can validate all tods files in testHarness directory', (filename) => {
  const data = JSON.parse(
    fs.readFileSync(`${sourcePath}/${filename}`, {
      encoding: 'utf8',
    }),
  );
  const result = validate(data);

  // to document pattern of use
  if (validate.errors) {
    const errors = ajv.errorsText(validate.errors, {
      dataVar: 'config',
    });
    console.log({ filename }, errors);
  }

  expect(result).toEqual(true);
});

const mockProfiles = [
  { drawProfiles: [{ drawSize: 32, drawType: MODIFIED_FEED_IN_CHAMPIONSHIP }] },
  { drawProfiles: [{ drawSize: 32, drawType: FIRST_ROUND_LOSER_CONSOLATION }] },
  { drawProfiles: [{ drawSize: 32, drawType: FIRST_MATCH_LOSER_CONSOLATION }] },
  { drawProfiles: [{ drawSize: 32, drawType: FEED_IN_CHAMPIONSHIP_TO_SF }] },
  { drawProfiles: [{ drawSize: 32, drawType: ROUND_ROBIN_WITH_PLAYOFF }] },
  { drawProfiles: [{ drawSize: 32, drawType: CURTIS_CONSOLATION }] },
  { drawProfiles: [{ drawSize: 32, drawType: ROUND_ROBIN }] },
  { drawProfiles: [{ drawSize: 32, drawType: COMPASS }] },
  { drawProfiles: [{ drawSize: 48, drawType: FEED_IN }] },
];

it.each(mockProfiles)('can validate tournaments generated by mocksEngine', (mockProfile) => {
  const { tournamentRecord } = mocksEngine.generateTournamentRecord(mockProfile);

  const result = validate(tournamentRecord);

  // to document pattern of use
  if (validate.errors) {
    const errors = ajv.errorsText(validate.errors, {
      dataVar: 'config',
      separator: ';',
    });
    console.log(errors);
    console.log(mockProfile);
    console.log(Object.keys(tournamentRecord.events[0].drawDefinitions[0].structures[1]));
    console.log(
      tournamentRecord.participants.map((p, i) => [i, p.person.addresses[0].countryCode]),
      tournamentRecord.events[0].drawDefinitions[0].structures[1].matchUps.map((m) => m.drawPositions),
    );
  }
  expect(result).toEqual(true);
});
