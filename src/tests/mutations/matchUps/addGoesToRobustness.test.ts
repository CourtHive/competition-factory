import { getAllDrawMatchUps } from '@Query/matchUps/drawMatchUps';
import { addGoesTo } from '@Query/matchUps/addGoesTo';
import mocksEngine from '@Assemblies/engines/mock';
import tournamentEngine from '@Engines/syncEngine';
import { describe, expect, it } from 'vitest';

import { MISSING_DRAW_DEFINITION } from '@Constants/errorConditionConstants';

/**
 * `inContextDrawMatchUps` and `matchUpsMap` are BOTH optional, so all four combinations
 * have to work. The map used to be built only inside `if (!inContextDrawMatchUps)`, so
 * passing the array without a map — "here are the matchUps I already flattened, enrich
 * them", the most natural integrator call — threw a bare
 * `Cannot read properties of undefined` from getMappedStructureMatchUps.
 */
function seed(drawType = 'FIRST_ROUND_LOSER_CONSOLATION') {
  const { tournamentRecord } = mocksEngine.generateTournamentRecord({
    tournamentAttributes: { tournamentId: `goesto-${drawType}` },
    drawProfiles: [{ drawSize: 16, drawType, eventName: 'Singles' }],
    startDate: '2025-01-01',
    endDate: '2025-01-14',
    nonRandom: 1,
  });
  tournamentEngine.setState(tournamentRecord);
  const drawId = tournamentRecord.events[0].drawDefinitions[0].drawId;
  const drawDefinition = tournamentEngine.getEvent({ drawId }).drawDefinition;
  // simulate a record whose progression edges were never materialised (older draws,
  // and TODS files not generated by the factory — addGoesTo's stated reason to exist)
  for (const structure of drawDefinition.structures ?? []) {
    for (const matchUp of structure.matchUps ?? []) delete matchUp.loserMatchUpId;
  }
  return { drawDefinition, drawId };
}

const loserCount = (matchUps: any[]) => matchUps.filter((m) => m.loserMatchUpId).length;

describe('addGoesTo argument robustness', () => {
  it('derives loser edges with NEITHER optional arg', () => {
    const { drawDefinition } = seed();
    const result: any = addGoesTo({ drawDefinition });
    expect(result.error).toBeUndefined();
    expect(loserCount(result.inContextDrawMatchUps)).toEqual(8);
    expect(Object.keys(result.goesToMap.loserMatchUpIds).length).toEqual(8);
  });

  it('derives loser edges with BOTH optional args', () => {
    const { drawDefinition } = seed();
    const { matchUps, matchUpsMap } = getAllDrawMatchUps({ inContext: true, drawDefinition });
    const result: any = addGoesTo({ drawDefinition, inContextDrawMatchUps: matchUps, matchUpsMap });
    expect(result.error).toBeUndefined();
    expect(loserCount(matchUps)).toEqual(8); // the caller's own array is enriched in place
  });

  it('derives loser edges given the ARRAY ONLY — the combination that used to throw', () => {
    const { drawDefinition } = seed();
    const { matchUps } = getAllDrawMatchUps({ inContext: true, drawDefinition });
    expect(loserCount(matchUps)).toEqual(0);

    const result: any = addGoesTo({ drawDefinition, inContextDrawMatchUps: matchUps });

    expect(result.error).toBeUndefined();
    expect(Object.keys(result.goesToMap.loserMatchUpIds).length).toEqual(8);
    // the caller's array must be the one enriched — not a replacement built internally
    expect(loserCount(matchUps)).toEqual(8);
    expect(result.inContextDrawMatchUps).toBe(matchUps);
  });

  it('derives loser edges given the MAP ONLY', () => {
    const { drawDefinition } = seed();
    const { matchUpsMap } = getAllDrawMatchUps({ inContext: true, drawDefinition });
    const result: any = addGoesTo({ drawDefinition, matchUpsMap });
    expect(result.error).toBeUndefined();
    expect(loserCount(result.inContextDrawMatchUps)).toEqual(8);
  });

  it('still rejects a missing drawDefinition', () => {
    expect(addGoesTo({} as any).error).toEqual(MISSING_DRAW_DEFINITION);
  });

  it('handles a draw type with no loser feed without inventing edges', () => {
    const { drawDefinition } = seed('SINGLE_ELIMINATION');
    const { matchUps } = getAllDrawMatchUps({ inContext: true, drawDefinition });
    const result: any = addGoesTo({ drawDefinition, inContextDrawMatchUps: matchUps });
    expect(result.error).toBeUndefined();
    expect(Object.keys(result.goesToMap.loserMatchUpIds).length).toEqual(0);
    expect(Object.keys(result.goesToMap.winnerMatchUpIds).length).toBeGreaterThan(0);
  });
});
